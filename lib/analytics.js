import { integrations } from "@/data/site";

/**
 * Отправка цели в Яндекс.Метрику из кода.
 *
 * Цели, настроенные в интерфейсе Метрики по классам кнопок, ломаются при
 * любой правке вёрстки — причём молча: отчёт просто перестаёт наполняться,
 * и это замечают через месяц. Событие из кода от вёрстки не зависит.
 *
 * Важно: само по себе событие цель не создаёт. В кабинете Метрики должна
 * быть заведена цель типа «JavaScript-событие» с таким же идентификатором.
 * Пока её нет, вызов просто ни к чему не приводит и ничего не ломает.
 *
 * Если посетитель не дал согласия на аналитику, счётчика на странице нет,
 * window.ym не существует — вызов тихо ничего не делает. Это правильное
 * поведение: не отслеживаем тех, кто отказался.
 */
export function reachGoal(goal, params) {
  if (typeof window === "undefined") return;
  const id = integrations.yandexMetrikaId;
  if (!id || typeof window.ym !== "function") return;

  try {
    window.ym(Number(id), "reachGoal", goal, params);
  } catch {
    /* аналитика не должна мешать работе формы */
  }
}

// Идентификаторы целей держим в одном месте, чтобы не разъехались с тем,
// что заведено в кабинете Метрики.
export const GOAL_LEAD = "lead";
