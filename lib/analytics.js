import { integrations } from "@/data/site";

/**
 * Отправка цели в счётчики из кода.
 *
 * Цели, настроенные в интерфейсе по классам кнопок, ломаются при любой
 * правке вёрстки — причём молча: отчёт просто перестаёт наполняться, и это
 * замечают через месяц. Событие из кода от вёрстки не зависит.
 *
 * Отправляем сразу в оба счётчика одним вызовом. Иначе рано или поздно
 * кто-то добавит событие в одно место и забудет про другое, и два отчёта
 * начнут показывать разные числа — а разбираться, какое верное, будет
 * некому.
 *
 * Если посетитель не дал согласия на аналитику, счётчиков на странице нет,
 * window.ym и window.gtag не существуют — вызовы тихо ничего не делают.
 * Это правильное поведение: не отслеживаем тех, кто отказался.
 */

// Идентификаторы держим здесь, чтобы они не разъехались с тем, что заведено
// в кабинетах.
//
// Для Метрики — цель типа «Целевое событие» с идентификатором lead.
// Для GA4 — имя generate_lead: это стандартное имя события из списка
// рекомендованных Google. Нестандартное тоже работает, но рекомендованные
// Google Ads подхватывает как конверсию без лишних настроек.
export const GOAL_LEAD = "lead";
export const GA4_LEAD = "generate_lead";

export function reachGoal(goal = GOAL_LEAD, params) {
  if (typeof window === "undefined") return;

  const { yandexMetrikaId, ga4Id } = integrations;

  if (yandexMetrikaId && typeof window.ym === "function") {
    try {
      window.ym(Number(yandexMetrikaId), "reachGoal", goal, params);
    } catch {
      /* аналитика не должна мешать работе формы */
    }
  }

  if (ga4Id && typeof window.gtag === "function") {
    try {
      window.gtag("event", goal === GOAL_LEAD ? GA4_LEAD : goal, params || {});
    } catch {
      /* то же самое */
    }
  }
}
