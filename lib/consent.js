/**
 * Согласие на аналитические куки.
 *
 * Баннер должен быть не декорацией, а работающим выключателем: если человек
 * выбрал «только необходимые», счётчик не должен загружаться вообще. Поэтому
 * выбор хранится здесь, а компонент Метрики спрашивает это значение перед
 * тем, как подключить скрипт.
 *
 * Что считаем необходимым. Онлайн-чат остаётся при любом выборе: это
 * единственный способ связаться с клиникой прямо со страницы, и человек
 * открывает его сам. Метрика — нет: она следит за всеми и ни для чего,
 * кроме нашей статистики, не нужна.
 *
 * Запоминание источника перехода (lib/utm.js) тоже оставлено при любом
 * выборе: данные лежат в собственном хранилище сайта и уходят к нам только
 * вместе с отправленной заявкой. Если юрист клиента решит иначе, достаточно
 * обернуть captureAttribution такой же проверкой.
 */

const KEY = "assuta_cookie_consent";
export const EVENT = "assuta:consent";

export const ALL = "all";
export const NECESSARY = "necessary";

/** "all" | "necessary" | null, если выбора ещё не было */
export function getConsent() {
  if (typeof window === "undefined") return null;
  try {
    const v = window.localStorage.getItem(KEY);
    return v === ALL || v === NECESSARY ? v : null;
  } catch {
    // Хранилище недоступно (приватный режим, запрет сторонних данных).
    // Считаем, что согласия нет: молчание — это не «да».
    return null;
  }
}

export function setConsent(value) {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(KEY, value);
  } catch {
    /* не сохранилось — баннер покажется снова, это честнее, чем молча включить */
  }
  // Сообщаем остальным компонентам, чтобы счётчик поднялся сразу, без
  // перезагрузки страницы.
  window.dispatchEvent(new CustomEvent(EVENT, { detail: value }));
}
