/**
 * Кто может открыть отчёт по источникам.
 *
 * Отчёт лежит не по простому адресу /report, а по адресу с секретным
 * хвостом: /report/<ключ>. Без него страница отвечает «не найдено» —
 * ровно так же, как любой несуществующий адрес, то есть по ответу сервера
 * нельзя даже понять, что такая страница существует.
 *
 * Почему так, а не пароль. Пароль на этом хостинге пришлось бы либо
 * задавать в панели управления (к ней не всегда есть доступ), либо писать
 * прямо здесь — и тогда он навсегда остался бы в истории изменений.
 * Секретный адрес — тот же компромисс, но с меньшей ценой ошибки: утечёт
 * не пароль, которым люди привыкли пользоваться и в других местах,
 * а одноразовая ссылка, которую меняют правкой одной строки.
 *
 * Что защищено. На странице только обобщённые числа по источникам.
 * Имён, телефонов и текстов обращений там нет и быть не должно —
 * см. getLeadStats в lib/sanity.js.
 *
 * ───────────────────────────────────────────────────────────────────
 * ЧТОБЫ СМЕНИТЬ ССЫЛКУ: впишите сюда новое случайное значение.
 * Старая ссылка сразу перестанет открываться.
 *
 * Если на сервере задана переменная окружения REPORT_KEY, используется
 * она — значение отсюда тогда не действует. Так ключ можно убрать из
 * репозитория, когда появится доступ к панели управления.
 * ───────────────────────────────────────────────────────────────────
 */
const FALLBACK_KEY = "zwqkd56xi5jpk9o8";

export const reportKey = () => process.env.REPORT_KEY || FALLBACK_KEY;

export const reportPath = () => `/report/${reportKey()}`;
