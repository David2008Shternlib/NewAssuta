// Врачи, относящиеся к категории заболевания
export function doctorsForCategory(category) {
  const map = {
    "Онкология": "Онкология",
    "Кардиология": "Кардиология",
    "Ортопедия": "Ортопедия",
    "Неврология и нейрохирургия": "Нейрохирургия",
    "Гастроэнтерология": "Гастроэнтерология",
    "Урология": "Урология",
  };
  const dept = map[category];
  const list = doctors.filter((d) => d.dept === dept);
  return list.length ? list : doctors.slice(0, 3);
}

